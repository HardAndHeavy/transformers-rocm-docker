#!/usr/bin/env python3
"""Single source of truth for the pinned software stack.

`versions.json` is the authoritative list of pinned versions. Everything else is
generated from it: the requirements inputs, the APT install block and the version
assertions in the Dockerfile, and the README stack table. The stack therefore
cannot drift between the four places it is written down.

Usage:
    python3 tools/versions.py check        # verify every generated block is current
    python3 tools/versions.py sync         # rewrite the generated files
    python3 tools/versions.py dockerfile   # print the Dockerfile assertion block
    python3 tools/versions.py apt          # print the Dockerfile APT block
    python3 tools/versions.py readme       # print the README version table
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSIONS_FILE = ROOT / "versions.json"

GENERATED_HEADER = "GENERATED by tools/versions.py from versions.json - do not edit by hand."

APT_BEGIN = "# BEGIN GENERATED: tools/versions.py apt\n"
APT_END = "# END GENERATED\n"
ASSERT_BEGIN = "# BEGIN GENERATED: tools/versions.py assertions\n"
ASSERT_END = "# END GENERATED\n"
README_BEGIN = "<!-- versions:begin -->\n"
README_END = "<!-- versions:end -->"


def load() -> dict:
    with VERSIONS_FILE.open(encoding="utf-8") as handle:
        return json.load(handle)


def requirements_in(data: dict) -> str:
    """ROCm wheels come from AMD, the rest from PyPI; this file feeds `make lock`."""
    return (
        f"# {GENERATED_HEADER}\n"
        "# CPython 3.14, Linux x86_64, ROCm 10.1.0.\n"
        "# Use stable PyTorch 2.13/torchvision 0.28: AMD published only the\n"
        "# incompatible torchvision 0.29.0a0 build for PyTorch 2.14 + ROCm 10.1.\n"
        "# See https://github.com/ROCm/TheRock/issues/8802.\n"
        + "".join(f"{name}=={version}\n" for name, version in data["requirements"].items())
    )


def bootstrap_in(data: dict) -> str:
    return (
        f"# {GENERATED_HEADER}\n"
        "# Installer and ROCm sdist build backend, pinned separately so the\n"
        "# main lock is installed by a known pip with a known setuptools.\n"
        "# The `rocm` package ships as an sdist whose build-system requires\n"
        "# setuptools>=70.2.0 (build-backend = setuptools.build_meta).\n"
        + "".join(f"{name}=={version}\n" for name, version in data["bootstrap"].items())
    )


def apt_block(data: dict) -> str:
    """APT sources frozen at one snapshot plus exact package versions.

    Installing `pkg=version` from the live archive breaks as soon as
    -updates/-security rotates the version out; a snapshot URL keeps the whole
    archive at a single instant, so the pins below stay resolvable forever.
    """
    series = data["image"]["ubuntu_series"]
    snapshot = data["image"]["ubuntu_snapshot"]
    packages = "".join(
        f"        {name}={version} \\\n" for name, version in data["apt"].items()
    ).rstrip(" \\\n")
    return (
        f"ARG APT_SNAPSHOT={snapshot}\n"
        "RUN set -eux; \\\n"
        "    printf '%s\\n' \\\n"
        "        'Types: deb' \\\n"
        '        "URIs: https://snapshot.ubuntu.com/ubuntu/${APT_SNAPSHOT}/" \\\n'
        f"        'Suites: {series} {series}-updates {series}-security' \\\n"
        "        'Components: main universe restricted multiverse' \\\n"
        "        'Signed-By: /usr/share/keyrings/ubuntu-archive-keyring.gpg' \\\n"
        "        > /etc/apt/sources.list.d/ubuntu.sources; \\\n"
        "    rm -f /etc/apt/sources.list.d/rocm.list; \\\n"
        "    apt-get update; \\\n"
        "    apt-get install -y --no-install-recommends \\\n"
        f"{packages}; \\\n"
        "    rm -rf /var/lib/apt/lists/*; \\\n"
        "    python3.14 -m venv /opt/venv\n"
    )


def assertion_block(data: dict) -> str:
    """The in-image assertion: the build fails if a lock ever resolves elsewhere."""
    expected = {
        "torch": data["requirements"]["torch[device-all]"],
        "torchvision": data["requirements"]["torchvision[device-all]"],
        "torchaudio": data["requirements"]["torchaudio"],
        "transformers": data["requirements"]["transformers"],
    }
    lines = [
        "RUN python - <<'PY'",
        "import torch",
        "import torchaudio",
        "import torchvision",
        "import transformers",
        "",
        "expected_versions = {",
    ]
    lines += [f'    "{name}": "{version}",' for name, version in expected.items()]
    lines += [
        "}",
        "",
        "for module in (torch, torchaudio, torchvision, transformers):",
        "    name = module.__name__",
        "    actual = module.__version__",
        "    assert actual == expected_versions[name], (name, actual)",
        "",
        'assert torch.version.hip is not None, "A ROCm-enabled PyTorch wheel is required"',
        'print(f"PyTorch: {torch.__version__}; HIP: {torch.version.hip}")',
        'print(f"torchvision: {torchvision.__version__}; torchaudio: {torchaudio.__version__}")',
        'print(f"Transformers: {transformers.__version__}")',
        "PY",
    ]
    return "\n".join(lines) + "\n"


def readme_table(data: dict) -> str:
    req = data["requirements"]
    rows = [
        ("Base OS", f"Ubuntu {data['image']['ubuntu_version']}"),
        ("ROCm", req["torch[device-all]"].split("+rocm")[-1]),
        ("Python", "3.14"),
        ("PyTorch", req["torch[device-all]"]),
        ("torchvision", req["torchvision[device-all]"]),
        ("torchaudio", req["torchaudio"]),
        ("Transformers", req["transformers"]),
        ("Accelerate", req["accelerate"]),
        ("PEFT", req["peft"]),
    ]
    body = "".join(f"| {name} | {version} |\n" for name, version in rows)
    return "| Component | Version |\n| --- | --- |\n" + body.rstrip("\n") + "\n"


def replace_between(text: str, begin: str, end: str, body: str) -> str:
    """Swap the content between two marker lines, keeping the markers."""
    head, marker, rest = text.partition(begin)
    if not marker:
        raise ValueError(f"marker not found: {begin.strip()!r}")
    _, marker, tail = rest.partition(end)
    if not marker:
        raise ValueError(f"marker not found: {end.strip()!r}")
    return head + begin + body + end + tail


def render(data: dict) -> dict[str, str]:
    """Every generated file, fully rendered: path -> expected content."""
    dockerfile = (ROOT / "Dockerfile").read_text(encoding="utf-8")
    dockerfile = replace_between(dockerfile, APT_BEGIN, APT_END, apt_block(data))
    dockerfile = replace_between(
        dockerfile, ASSERT_BEGIN, ASSERT_END, assertion_block(data)
    )
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    readme = replace_between(readme, README_BEGIN, README_END, readme_table(data))
    return {
        "requirements.in": requirements_in(data),
        "requirements-bootstrap.in": bootstrap_in(data),
        "Dockerfile": dockerfile,
        "README.md": readme,
    }


def sync() -> int:
    data = load()
    changed = []
    for name, content in render(data).items():
        path = ROOT / name
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
            changed.append(name)
    print("updated: " + ", ".join(changed) if changed else "everything already current")
    return 0


def check() -> int:
    stale = [
        name
        for name, content in render(load()).items()
        if (ROOT / name).read_text(encoding="utf-8") != content
    ]
    if stale:
        print("out of date, run `make versions`: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("versions.json is in sync")
    return 0


def main(argv: list[str]) -> int:
    command = argv[1] if len(argv) > 1 else "check"
    data = load()
    printers = {
        "dockerfile": assertion_block,
        "apt": apt_block,
        "readme": readme_table,
    }
    if command in printers:
        print(printers[command](data), end="")
        return 0
    if command == "sync":
        return sync()
    if command == "check":
        return check()
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
